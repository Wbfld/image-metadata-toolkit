import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { join, resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const manifestPath = join(root, "scripts/capabilities-manifest.json");
const outputPath = join(root, "CAPABILITIES.md");
const manifest = JSON.parse(await readFile(manifestPath, "utf8"));

function digest(value) {
  return createHash("sha256").update(value).digest("hex");
}

function yes(value) {
  if (typeof value === "boolean") return value;
  return typeof value === "string" && value.trim().toLowerCase() !== "no" && value.trim().length > 0;
}

function cell(value) {
  return typeof value === "boolean" ? (value ? "Yes" : "No") : value;
}

function render(manifestText) {
  const hash = digest(manifestText);
  const headers = manifest.matrixColumns.map(({ label }) => label);
  const lines = [
    `# ${manifest.brand} capability matrix`,
    "",
    `<!-- Generated by scripts/generate-capabilities.mjs from scripts/capabilities-manifest.json; manifest-sha256: ${hash} -->`,
    "",
    `This matrix describes the \`${manifest.brand}\` 2.0 alpha surface. It is generated from the checked-in capability manifest and is intentionally narrower than format detection: a container can be recognized even when a particular metadata family or modification is not implemented.`,
    "",
    "Detection is signature recognition only. A detected format does not imply that every metadata family, read scope, redaction target, or rewrite operation is supported.",
    "",
    `| Container | ${headers.join(" | ")} |`,
    `| --- | ${headers.map(() => "---").join(" | ")} |`,
    ...manifest.formats.map((format) => `| ${format.format} | ${manifest.matrixColumns.map(({ key }) => cell(format[key])).join(" | ")} |`),
    "",
    "`selectiveDecode` means the reader avoids decoding unrequested EXIF fields and metadata families where that container supports selection. A `Yes` or partial scope is still bounded by the parser's limits and may fall back to a full read for unsupported or malformed layouts.",
    "",
    "`jpegHeaderBlobRead` and `metadataBlobFileRead` describe Blob/File range behavior. Partial reads report `completeness.scope`, `bytesRead`, `inputBytes`, and machine-readable `coverage.reasons`.",
    "",
    "Every affirmative matrix cell carries positive, malformed, and selection evidence in the manifest. The capability contract test validates that evidence remains present when a claim is changed.",
    "",
    "## Evidence map",
    "",
    "| Container | Positive test | Malformed test | Selection test |",
    "| --- | --- | --- | --- |",
    ...manifest.formats.map((format) => `| ${format.format} | ${format.evidence.positive} | ${format.evidence.malformed} | ${format.evidence.selection} |`),
    "",
    "## Removal semantics",
    "",
    "Removal copies encoded image payloads without recompressing pixels. JPEG entropy-coded scan data, PNG IDAT data, and WebP image chunks remain encoded as they were. JPEGs with MPF secondary images or Ultra HDR gain-map XMP are refused atomically until their offset relationships can be rewritten safely.",
    "",
    "`redactMetadata()` reports every operation through `outcome`. A successful outcome means every requested target that is supported for the detected format was handled; it does not mean unknown container data has been interpreted. `auditPrivacy()` identifies recognized sensitive values, opaque blocks, thumbnails, trailing data, warnings, and inspection gaps before a sharing workflow makes a policy decision.",
    "",
    "`sanitizeMetadata()` is the strict sharing API. It preserves ICC information and EXIF orientation by default, removes recognized descriptive metadata, and returns bytes only when the policy has been satisfied. Callers must check both `successful` and `data`.",
    "",
    "```ts",
    "const result = await sanitizeMetadata(file);",
    "if (result.successful && result.data !== null) await share(result.data);",
    "else showReasons(result.reasons);",
    "```",
    "",
    "## Input and runtime support",
    "",
    "The public input type is `ArrayBuffer`, any `ArrayBufferView`, `Blob`, or `File`. The core parser does not fetch URLs, paths, or network resources. The separate `browser-image-metadata/fetch` entry point provides opt-in, input-bounded response streaming for browser and compatible runtime fetch implementations.",
    "",
    "The published package includes ESM, CommonJS, source maps, declarations, focused detection/fetch/JPEG/redaction/XMP/worker entry points, and a dependency-free core. Node.js 22 or newer is covered in CI; browser, worker, Node, and Deno usage examples are included.",
    "",
    "## Explicit limitations",
    "",
    ...manifest.notes.map((note) => `- ${note}`),
    "- ICC inspection is limited to the profile header and bounded tag directory; it does not interpret color transforms or arbitrary tag payloads.",
    "- MakerNote interpretation, image sequences, complete HEIF/AVIF item-property semantics, and TIFF/WebP/HEIF/AVIF writing remain unsupported.",
    "- EXIF date strings do not imply a timezone unless a separate offset tag exists.",
    "",
  ];
  return lines.join("\n");
}

const manifestText = `${JSON.stringify(manifest, null, 2)}\n`;
const generated = render(manifestText);
if (process.argv.includes("--check")) {
  const existing = await readFile(outputPath, "utf8");
  if (existing !== generated) {
    console.error("CAPABILITIES.md is stale. Run npm run capabilities:generate.");
    process.exitCode = 1;
  } else {
    console.log("CAPABILITIES.md is up to date.");
  }
} else {
  await writeFile(outputPath, generated);
  console.log(`Generated ${outputPath} from ${manifestPath}.`);
}

export { render, yes };
